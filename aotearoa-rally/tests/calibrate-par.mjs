// Generates core/partimes.mjs: skill-1.0 bot laps for every stage x car (par = what a clean, sensible drive takes).
//   node aotearoa-rally/tests/calibrate-par.mjs        (writes core/partimes.mjs and prints the table)
//   node aotearoa-rally/tests/calibrate-par.mjs --dry  (prints only)
import os from "node:os"; os.setPriority(0, os.constants.priority.PRIORITY_LOW);
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { CAR_IDS } from "../core/cars.mjs";
import { STAGE_IDS, buildStage } from "../core/stage.mjs";
import { botLap } from "./dynamics-botrun.mjs";

const dry = process.argv.includes("--dry");
const t0 = performance.now();
const par = {};
let bad = 0;
console.log("stage".padEnd(14) + CAR_IDS.map((c) => c.padStart(11)).join(""));
for (const sid of STAGE_IDS) {
  const st = buildStage(sid);
  par[sid] = {};
  let row = sid.padEnd(14);
  for (const id of CAR_IDS) {
    const r = botLap(sid, id, 1, st);
    if (!r.finished || r.offRoad > 2) { bad++; console.error(`WARNING ${sid}/${id}: finished=${r.finished} off-road=${r.offRoad.toFixed(1)} s`); }
    par[sid][id] = Math.round(r.time * 10) / 10;
    row += par[sid][id].toFixed(1).padStart(11);
  }
  console.log(row);
}
console.log(`done in ${((performance.now() - t0) / 1000).toFixed(1)} s, problems: ${bad}`);

if (!dry) {
  if (bad) { console.error("refusing to write partimes.mjs while the bot has problems"); process.exit(1); }
  const lines = ["// GENERATED by tests/calibrate-par.mjs (skill-1.0 bot laps, 120 Hz physics). Do not edit by hand.", "export const PAR_TIMES = {"];
  for (const sid of STAGE_IDS) lines.push(`  ${sid}: { ${CAR_IDS.map((c) => `${c}: ${par[sid][c].toFixed(1)}`).join(", ")} },`);
  lines.push("};", "");
  writeFileSync(fileURLToPath(new URL("../core/partimes.mjs", import.meta.url)), lines.join("\n"));
  console.log("wrote core/partimes.mjs");
}
