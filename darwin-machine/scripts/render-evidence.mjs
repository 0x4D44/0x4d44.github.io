import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const readJson = async (name) => JSON.parse(await readFile(resolve(ROOT, `reports/${name}`), "utf8"));
const trace = await readJson("ancestor-trace.json");
const neighbourhood = await readJson("mutational-neighbourhood.json");
const assays = await readJson("evolutionary-assays.json");
const benchmark = await readJson("native-benchmark.json");
const search = await readJson("replicator-search.json");

const percentage = (part, total) => total ? `${(part * 100 / total).toFixed(2)}%` : "0%";
const assayGroup = (name) => assays.filter((row) => row.preset === name);
const median = (values) => {
  if (!values.length) return 0;
  const ordered = [...values].sort((a,b) => a-b);
  return ordered[Math.floor(ordered.length / 2)];
};

let md = `# Generated implementation evidence\n\n`;
md += `This report is generated by \`scripts/build-wasm.sh\` from the native Rust core. It is evidence for this exact build, not a general biological claim.\n\n`;
md += `## Ancestor reproduction contracts\n\n`;
for (const [name, row] of Object.entries(trace)) {
  md += `- **${name}**: divided=${row.child_divided}; exact child=${row.exact_child}; first division instructions=${row.first_division_instructions ?? "none"}; genome bytes=${row.genome_length}.\n`;
}
md += `\n## One-step mutational neighbourhoods\n\n`;
for (const row of neighbourhood) {
  md += `### ${row.ancestor}\n\n`;
  md += `- substitutions tested: ${row.substitutions_tested}; viable: ${row.substitutions_child_divided} (${percentage(row.substitutions_child_divided,row.substitutions_tested)})\n`;
  md += `- deletions tested: ${row.deletions_tested}; viable: ${row.deletions_child_divided} (${percentage(row.deletions_child_divided,row.deletions_tested)})\n`;
  md += `- insertions tested: ${row.insertions_tested}; viable: ${row.insertions_child_divided} (${percentage(row.insertions_child_divided,row.insertions_tested)})\n`;
  md += `- faster exact replicators found: ${row.substitutions_faster}; shorter exact replicators found: ${row.deletions_child_divided}\n\n`;
}
md += `## Replicator discovery and damage search\n\n`;
for (const row of search.damaged_ancestor) {
  md += `- ${row.edits} random edit(s) to the 64-byte ancestor: ${row.child_divided}/${row.trials} retained second-generation replication.\n`;
}
md += `- random private-genome programs: ${search.random_programs.child_divided}/${search.random_programs.trials} produced a second generation within ${search.horizon_instructions.toLocaleString("en-GB")} instructions. This finite result is not an abiogenesis claim.\n\n`;
md += `## Multi-seed evolutionary assays\n\n`;
for (const preset of ["faster-smaller","mutation-meltdown","bottleneck"]) {
  const rows = assayGroup(preset);
  md += `### ${preset}\n\n`;
  md += `Across ${rows.length} seeds after ${rows[0]?.updates ?? 0} updates: median population ${median(rows.map(r=>r.population))}, median exact genotypes ${median(rows.map(r=>r.genotypes))}, median genome length ${median(rows.map(r=>r.median_genome_length))} bytes. Raw per-seed outcomes remain in \`evolutionary-assays.json\`.\n\n`;
}
md += `## Native throughput\n\n`;
md += `The build gate executed ${benchmark.instructions.toLocaleString("en-GB")} organism instructions over ${benchmark.updates.toLocaleString("en-GB")} updates and reached checksum \`${benchmark.checksum}\`. Wall-clock throughput is emitted to the CI log rather than committed, so rebuild-and-diff remains exact across runners.\n`;

await writeFile(resolve(ROOT, "reports/evidence.md"), md);
