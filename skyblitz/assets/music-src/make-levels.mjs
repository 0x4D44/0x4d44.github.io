// Generates src/audio/levels.js: a per-SFX gain so every one-shot lands at a chosen peak level (dBFS) before the buses.
// Input: JSON from the offline render harness ({rows:[{name, peakDb}]}, see tests/audio.test.mjs / tests/lab/audio-offline.html).
//   node make-levels.mjs <sfxtable.json>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const rows = JSON.parse(fs.readFileSync(process.argv[2], 'utf8')).rows;
// target peak (dBFS) by sound role: UI is quiet, alerts cut through, weapons/impacts are the loudest (the master limiter catches them)
const T = [
  [/^(ui|camTick)/, -11], [/^(beingLocked)$/, -10], [/^(rollNow)$/, -5], [/^(stormCast|thunderFar)$/, -6], [/^(countBeep|goBeep|warnBeep|lockTick|lockSolid|wrongWay|stall|overheat)$/, -6], [/^(finalLap|lap|rocket|winJingle|loseJingle)$/, -6],
  [/^(gate|gatePerfect|orb|itemReady|stunt|recover|respawn)$/, -8], [/Whoosh$|^(nearMiss|evade|overtake|passed|shortcut|ringBoost|smoke|boostIgnite)$/, -7],
  [/^(cannon|cannonHit|mineDrop)$/, -13], [/^(tumble)$/, -8], [/^(explosion|hitThump|lightning|mineBlast|emp|shieldBlock)$/, -4],
  [/^(missileLaunch|shieldUp|shieldDown|droneLaunch)$/, -5],
];
const out = {};
for (const r of rows) {
  const t = (T.find(([re]) => re.test(r.name)) || [null, -6])[1];
  out[r.name] = Number(Math.pow(10, (t - r.peakDb) / 20).toFixed(3));
}
const src = `// GENERATED by assets/music-src/make-levels.mjs from the offline renders - per-SFX gain so each one-shot peaks at its role's level.
// Re-run after changing a recipe in sfx.js:  node assets/music-src/make-levels.mjs <sfxtable.json>
export const LEVEL = ${JSON.stringify(out, null, 1).replace(/\n\s+/g, ' ').replace(/\n}/, ' }')};
`;
fs.writeFileSync(path.join(HERE, '..', '..', 'src', 'audio', 'levels.js'), src);
console.log('levels.js written', Object.keys(out).length);
