// Builds ../stars.js from a Simbad TSV (see query below). Run:
//   node tools/build-stars.mjs stars.tsv > stars.js
// Query (Simbad TAP, FORMAT=tsv):
//   SELECT main_id, ra, dec, plx_value, V FROM basic LEFT JOIN allfluxes ON basic.oid=allfluxes.oidref
//   WHERE plx_value>32.616 AND plx_err<plx_value/8
// 32.616 mas = 100 light-years. Positions are J2000, proper motion ignored (<0.01% of a shell radius).
import { readFileSync } from "node:fs";
const rows = readFileSync(process.argv[2], "utf8").split("\n").slice(1).filter(Boolean).map(l => {
  const f = l.split("\t");
  return { id: f[0].replace(/^"|"$/g, ""), ra: +f[1], dec: +f[2], plx: +f[3], v: f[4] === "" ? null : +f[4] };
});
