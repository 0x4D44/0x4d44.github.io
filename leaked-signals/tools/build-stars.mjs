function pretty(id) {
  if (COMMON[id]) return COMMON[id];
  let s = id.replace(/^NAME /, "").replace(/^\*+\s+/, "").replace(/^V\*\s+/, "").replace(/\s+/g, " ").trim();
  const m = s.match(/^([a-z]{2,3})(\d*)\.? ([A-Za-z]{2,4})$/);
  if (m && GREEK[m[1]]) s = `${GREEK[m[1]]}${m[2] ? " " + m[2] : ""} ${m[3]}`;
  return s;
}
const isPlanet = id => /(\s|^)[b-i]$/.test(id) || /\d[b-i]$/.test(id) || /\s[b-i]$/.test(id);
// dedupe: same position/parallax => keep the entry with a V magnitude and the simplest name
const key = r => `${r.ra.toFixed(3)}|${r.dec.toFixed(3)}`;
const best = new Map();
for (const r of rows) {
  const k = key(r), cur = best.get(k);
  const score = x => (x.v != null ? 10 : 0) - (isPlanet(x.id) ? 20 : 0) - (/^NAME/.test(x.id) ? 0 : 0) - x.id.length * 0.01;
  if (!cur || score(r) > score(cur)) best.set(k, r);
}
const list = [...best.values()].filter(r => !isPlanet(r.id) || r.v != null).sort((a, b) => b.plx - a.plx);
const ra = [], dec = [], ly = [], v = [], names = {};
list.forEach((r, i) => {
  const d = 3261.5637 / r.plx; // ly
  ra.push(+r.ra.toFixed(3)); dec.push(+r.dec.toFixed(3)); ly.push(+d.toFixed(2));
  v.push(r.v == null ? null : +r.v.toFixed(1));
  const named = COMMON[r.id] || (r.v != null && r.v < 6.5) || d < 16 || /^NAME/.test(r.id);
  if (named) names[i] = pretty(r.id);
});
process.stdout.write(`// Generated by tools/build-stars.mjs from Simbad (stars within 100 ly, parallax S/N > 8). Do not hand-edit.\n` +
  `window.LEAK_STARS=${JSON.stringify({ n: list.length, ra, dec, ly, v, names })};\n`);
console.error("stars:", list.length, "named:", Object.keys(names).length);
