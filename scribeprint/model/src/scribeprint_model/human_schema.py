def load_profile(path: str | Path) -> tuple[BenchmarkProfile, str]:
    path = Path(path)
    source = path.read_text(encoding="utf-8")
    profile = BenchmarkProfile.model_validate_json(source)
    canonical = json.dumps(json.loads(source), sort_keys=True, separators=(",", ":"))
    return profile, _sha256(canonical)
