"""Parametric station generator: builds models/station_<id>.glb (platform hall) and models/station_<id>_entrance.glb for all 15 stations,
driven by data/station_looks.json (A1) + data/subway.json platform types.  Textures are UV-mapped/embedded (generated by assets_tex.py).

HALL frame (Blender -> glTF): origin = hall centre on the hall centre-line at RAIL-HEAD level; tracks run along Y (glTF -Z / +Z),
hall spans y in [-27, +27] (platform 45 m = +-22.5 m).  Track centre-lines at x = +-trackX (see station_<id>.json beside each glb).
"""
import math, sys, os, json
sys.path.insert(0, os.path.dirname(__file__))
from assets_lib import *
import assets_tex
from assets_tunnel import add_track, R as BORE_R, ZC, FLOOR_Z

PH = 0.695                 # platform height (= floor height of the train)
HL = 27.0                  # hall half length
PL = 22.5                  # platform half length (45 m)
HALF_TRAIN = 1.155
GAPW = 0.09                # train-to-platform-edge gap
FZ = FLOOR_Z

def hexrgb(h):
    h = h.lstrip('#'); return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))

def luminance(h):
    r, g, b = hexrgb(h); return 0.2126 * r + 0.7152 * g + 0.0722 * b

def load_looks():
    p = os.path.join(ROOT, 'data', 'station_looks.json')
    d = json.load(open(p))['stations']
    return {s['id']: s for s in d}

def derive(look):
    """Turn a station_looks.json entry into generator parameters."""
    pt = look['platform']['type']
    pw = float(look['platform']['widthM'])
    shape = look['vault']['shape'].lower()
    coved = ('ribbed' in shape or 'curved' in shape) and 'no ring vault' not in shape and pt != 'side'
    W = float(look['vault']['widthM'])
    vh = float(look['vault']['heightM'])
    ceil_txt = (look['ceiling'].get('material', '') + ' ' + shape).lower()
    cm = look['ceiling'].get('material', '').lower().split('(pre-refit')[0]
    cm_all = look['ceiling'].get('material', '').lower()
    if 'timber' in cm or ('timber' in cm_all and 'pre-refit' in cm_all and cm.strip().endswith('timber-slat ceiling')): soffit = 'timber'
    elif 'silver' in cm or 'metal' in cm or 'lay-in' in cm or 'mineral' in cm or 'white' in cm: soffit = 'metal'
    else: soffit = 'dark'
    wt = look['wallTile']
    b1, b2 = wt.get('bandHex', '#F0601A'), wt.get('accentHex', '#3A3F46')
    # outer band = the more orange/saturated one, inner = the darker/charcoal one (Hillhead: both dark)
    def sat(h):
        r, g, b = hexrgb(h); return r - b
    outer, inner = (b1, b2) if sat(b1) >= sat(b2) else (b2, b1)
    floor_hex = look['floor']['hex']
    return dict(id=look['id'], name=look['id'].replace('-', ' ').title().replace("St George'S", "St George's").replace("St Georges", "St George's"),
                type=pt, pw=pw, coved=coved, width=W, vh=vh,
                vault_hex=look['vault']['colours'][0], vault2_hex=(look['vault']['colours'] + ['#2A2B2D'])[1],
                wall_hex=wt['hex'], band_outer=outer, band_inner=inner,
                floor_hex=floor_hex, floor_brick=(luminance(floor_hex) > 150 and sat(floor_hex) > 40),
                soffit=soffit, soffit_hex=look['ceiling']['hex'],
                pillars=bool(look.get('pillars')), pat=wt.get('pattern', '').lower(),
                psd=look['id'] in ('govan', 'partick', 'ibrox'), mural=look.get('mural'),
                ent_style=look['entrance']['style'].lower(), ent_hex=look['entrance'].get('hexes', ['#6B5A50']),
                features=look.get('features', []))

NAMES = {'st-georges-cross': "St George's Cross", 'st-enoch': 'St Enoch', 'buchanan-street': 'Buchanan Street', 'bridge-street': 'Bridge Street', 'west-street': 'West Street',
         'shields-road': 'Shields Road', 'kinning-park': 'Kinning Park', 'cessnock': 'Cessnock', 'ibrox': 'Ibrox', 'govan': 'Govan', 'partick': 'Partick',
         'kelvinhall': 'Kelvinhall', 'hillhead': 'Hillhead', 'kelvinbridge': 'Kelvinbridge', 'cowcaddens': 'Cowcaddens'}

def mv(name, src, hexc_, **kw):
    """material variant: copy PALETTE[src] with a new tint."""
    h, me, ro, em, es, al, tx = PALETTE[src]
    new_mat(name, hexc_, kw.get('metal', me), kw.get('rough', ro), kw.get('em', em), kw.get('es', es), kw.get('alpha', al), kw.get('tex', tx))
    return name

def wall_line(m, pts, mat, **kw):
    m.strip_y(pts, -HL, HL, mat, **kw)

def quad_wall(m, x, y0, y1, z0, z1, mat, facing, rect, flip_text=False):
    """Flat quad on a wall at x spanning y0..y1, z0..z1, front face looking toward `facing` (+1 = +x)."""
    # viewer looks along -facing; viewer's right = ... for facing=+1 viewer faces -x: right = -y?  (Blender: looking -x, right is -y? computed: right = up x forward)
    if facing > 0:
        p = (y1, y0)
    else:
        p = (y0, y1)
    f = m.quad_uv((x, p[0], z0), (x, p[1], z0), (x, p[1], z1), (x, p[0], z1), mat, rect)
    f[m.fx] = 1
    if f.normal.x * facing < 0: f.normal_flip()
    return f

def build_hall(cfg, out_json):
    reset()
    sid = cfg['id']; name = NAMES[sid]
    root = group(f'station_{sid}')
    t = cfg['type']
    # ------------------------------------------------ layout
    if t == 'island':
        pwid = cfg['pw']; ph = pwid / 2; tx = ph + GAPW + HALF_TRAIN; HWL = HWR = cfg['width'] / 2
        tracks = [-tx, tx]; plats = [(-ph, ph)]
    elif t == 'side':
        HWL = HWR = cfg['width'] / 2; pwid = cfg['pw']
        tx = HWR - pwid - GAPW - HALF_TRAIN
        tracks = [-tx, tx]; plats = [(-HWL, -(tx + HALF_TRAIN + GAPW)), (tx + HALF_TRAIN + GAPW, HWR)]
    else:  # split: island + side platform beyond the right-hand track
        pwid = cfg['pw']; ph = pwid / 2; tx = ph + GAPW + HALF_TRAIN
        HWL = cfg['width'] / 2; HWR = HWL + 3.2
        tracks = [-tx, tx]; plats = [(-ph, ph), (tx + HALF_TRAIN + GAPW, HWR)]
    need = tx + BORE_R + 0.5           # the bore circle + brick collar must fit inside the hall outline at the end wall
    if t == 'island': HWL = HWR = max(HWL, need)
    elif t == 'split': HWL = max(HWL, need)
    soffit_z = PH + cfg['vh']
    spring = 2.3
    coved = cfg['coved']
    # ------------------------------------------------ materials (station tinted)
    sid_ = sid.replace('-', '_')
    wall_tile = mv(f'wall_{sid_}', 'tile_cream', cfg['wall_hex'], tex='tile_brick' if 'rectangular' in cfg['pat'] or 'stacked' in cfg['pat'] else 'tile')
    vault_mat = mv(f'vault_{sid_}', 'tile_cream', cfg['vault_hex'], tex='enamel', rough=0.3)
    dado_mat = mv(f'dado_{sid_}', 'tile_cream', cfg['wall_hex'] if not coved else cfg['vault_hex'], tex='tile')
    if cfg['id'] == 'partick': dado_mat = mv(f'dado_{sid_}', 'tile_cream', '#e9e9e6', tex='tile')
    floor_mat = mv(f'floor_{sid_}', 'platform_floor', cfg['floor_hex'], tex='tile_brick' if cfg['floor_brick'] else 'flags', rough=0.55)
    edge_mat = mv(f'edge_{sid_}', 'edge_white', '#e6dc9a', rough=0.5)
    tact_mat = mv(f'tactile_{sid_}', 'tactile_yellow', '#59606a' if not cfg['floor_brick'] else '#59606a', tex='tactile')
    loz_mat = mv(f'lozenge_{sid_}', 'tactile_yellow', '#5a6068', tex='lozenge')
    sof_hex = cfg['soffit_hex']
    if cfg['soffit'] == 'timber': soffit_mat = mv(f'soffit_{sid_}', 'wood_bench', sof_hex, tex='timber', rough=0.7)
    elif cfg['soffit'] == 'metal': soffit_mat = mv(f'soffit_{sid_}', 'panel_ceiling', sof_hex, tex='ceiling_panel', rough=0.35, metal=0.4)
    else: soffit_mat = mv(f'soffit_{sid_}', 'panel_ceiling', sof_hex, tex='plaster', rough=0.8)
    mouth_hex = '#5a3a30' if sid != 'partick' else '#4a3a34'
    brick_mat = mv(f'mouthbrick_{sid_}', 'brick_dark', mouth_hex)
    t_tex = assets_tex.station_name_textures(sid, name.upper() if False else name, hexrgb(cfg['band_outer']), hexrgb(cfg['band_inner']))
    register_tex(f'band_outer_{sid_}', t_tex['band_outer']); register_tex(f'band_inner_{sid_}', t_tex['band_inner']); register_tex(f'board_{sid_}', t_tex['board'])
    register_tex('dir_inner', t_tex['dir_inner']); register_tex('dir_outer', t_tex['dir_outer'])
    new_mat(f'bandmat_outer_{sid_}', '#ffffff', 0, 0.35, tex=f'band_outer_{sid_}')
    new_mat(f'bandmat_inner_{sid_}', '#ffffff', 0, 0.35, tex=f'band_inner_{sid_}')
    new_mat(f'board_{sid_}', '#ffffff', 0, 0.4, em='tex', es=0.5, tex=f'board_{sid_}')
    new_mat('dirsign_inner', '#ffffff', 0, 0.4, tex='dir_inner'); new_mat('dirsign_outer', '#ffffff', 0, 0.4, tex='dir_outer')
    new_mat('stencil_danger', '#ffffff', 0, 0.8, tex='danger')
    new_mat('fence_mesh', '#ffffff', 0, 0.6, alpha=0.99, tex='mesh')
    new_mat('mural_mat', '#ffffff', 0, 0.5, tex='art_hillhead')
    # ------------------------------------------------ profile of the hall (x, z) : walls + ceiling
    def ellipse(cx, cz, a, b, t0, t1, n=14):
        return [(cx + a * math.cos(math.radians(t0 + (t1 - t0) * i / n)), cz + b * math.sin(math.radians(t0 + (t1 - t0) * i / n))) for i in range(n + 1)]
    shell = M(); trim = M(); signs = M(); furn = M(); lights = M(); mouths = M(); psdm = M(); art = M()
    def ceil_z(x):
        if coved:
            ax = abs(x)
            if ax <= 1.6 or (t == 'split' and x > 0): return soffit_z
            HWs = HWL if x < 0 else HWR
            u = min(1.0, (ax - 1.6) / max(0.01, HWs - 1.6))
            return spring + (soffit_z - spring) * math.sqrt(max(0.0, 1 - u * u))
        cxx = (HWR - HWL) / 2; aa = (HWL + HWR) / 2
        return 2.9 + (soffit_z - 2.9) * math.sqrt(max(0.0, 1 - ((x - cxx) / aa) ** 2))
    if coved:
        sx0 = 1.6
        # left: wall to spring, then quarter ellipse up to (-1.6, soffit)
        left_cove = ellipse(-sx0, spring, HWL - sx0, soffit_z - spring, 180, 90, 14)       # from (-HWL, spring) to (-sx0, soffit)
        right_cove = ellipse(sx0, spring, HWR - sx0, soffit_z - spring, 90, 0, 14) if t != 'split' else None
        if t == 'split':
            # split: right side is a flat box over the side platform
            right_cove = [(sx0, soffit_z), (HWR, soffit_z)]
        wall_line(shell, [(-HWL, FZ), (-HWL, 1.35)], dado_mat, toward=(0, 1.2))
        wall_line(shell, [(-HWL, 1.35), (-HWL, spring)], vault_mat, toward=(0, 1.2), uv=(0.5, HL * 2 / 1.0))
        m_ = M()
        # coved surfaces with panel UVs (enamel ribs 0.65 m wide)
        def cove_strip(pts, mat):
            L = sum(math.hypot(pts[i + 1][0] - pts[i][0], pts[i + 1][1] - pts[i][1]) for i in range(len(pts) - 1))
            shell.strip_y(pts, -HL, HL, mat, toward=(0.0, 1.2), uv=(L / 0.65, HL * 2 / 1.0))
        cove_strip(left_cove, vault_mat)
        if t == 'island':
            cove_strip(right_cove, vault_mat)
            wall_line(shell, [(HWR, spring), (HWR, 1.35)], vault_mat, toward=(0, 1.2), uv=(0.5, HL * 2 / 1.0))
            wall_line(shell, [(HWR, 1.35), (HWR, FZ)], dado_mat, toward=(0, 1.2))
            wall_line(shell, [(-sx0, soffit_z), (sx0, soffit_z)], soffit_mat, toward=(0, 1.2))
        else:
            wall_line(shell, [(-sx0, soffit_z), (HWR, soffit_z)], soffit_mat, toward=(0, 1.2))
            wall_line(shell, [(HWR, soffit_z), (HWR, FZ)], wall_tile, toward=(0, 1.2))
    else:
        spring_b = 2.9
        cx_ = (HWR - HWL) / 2; a_ = (HWL + HWR) / 2; b_ = soffit_z - spring_b
        arch = ellipse(cx_, spring_b, a_, b_, 180, 0, 32)          # from (-HWL, spring) over the crown to (HWR, spring)
        wall_line(shell, [(-HWL, FZ), (-HWL, 2.45)], dado_mat, toward=(0, 1.2))
        wall_line(shell, [(-HWL, 2.45), (-HWL, spring_b)], wall_tile, toward=(0, 1.2))
        wall_line(shell, [(HWR, spring_b), (HWR, 2.45)], wall_tile, toward=(0, 1.2))
        wall_line(shell, [(HWR, 2.45), (HWR, FZ)], dado_mat, toward=(0, 1.2))
        alen = sum(math.hypot(arch[i + 1][0] - arch[i][0], arch[i + 1][1] - arch[i][1]) for i in range(len(arch) - 1))
        shell.strip_y(arch, -HL, HL, soffit_mat, toward=(cx_, 1.2), uv=(alen / 1.0, HL * 2 / 1.0))
    # floor between walls + platforms
    shell.quad((-HWL, -HL, FZ), (HWR, -HL, FZ), (HWR, HL, FZ), (-HWL, HL, FZ), 'concrete_dark')
    # ------------------------------------------------ platforms
    ends = []   # platform ramps
    for (xa, xb) in plats:
        shell.bbox((xa, -PL, FZ), (xb, PL, PH - 0.02), 'platform_stone')
        shell.bbox((xa, -PL, PH - 0.02), (xb, PL, PH), floor_mat)
        # platform ends: ramp down to the track bed (island only; side platforms end square)
        if t != 'side':
            for sgy in (-1, 1):
                shell.prism_x([(sgy * PL, PH), (sgy * PL, FZ), (sgy * (PL + 3.4), FZ)], xa, xb, floor_mat)
    # edge strips, tactile strips, lozenge line, platform fronts
    edges = []
    for tx_ in tracks:
        for (xa, xb) in plats:
            for e, nrm in ((xa, 1), (xb, -1)):
                # does this platform edge face this track?
                if abs(abs(e - tx_) - (HALF_TRAIN + GAPW)) < 0.02:
                    inward = 1 if (xa if e == xa else xb) < tx_ else -1
                    edges.append((e, tx_, 1 if tx_ > e else -1))
    for (e, tx_, d) in edges:        # d = direction from platform edge toward track (+1 / -1)
        x_edge_in = e - d * 0.0
        # edge strip: outermost 0.10 m ; tactile: next 0.60 m (inboard)
        trim.bbox((min(e, e - d * 0.10), -PL, PH), (max(e, e - d * 0.10), PL, PH + 0.004), edge_mat)
        trim.bbox((min(e - d * 0.10, e - d * 0.70), -PL, PH), (max(e - d * 0.10, e - d * 0.70), PL, PH + 0.012), tact_mat)
        if cfg['id'] == 'govan':
            trim.bbox((min(e - d * 1.1, e - d * 1.4), -PL, PH), (max(e - d * 1.1, e - d * 1.4), PL, PH + 0.012), loz_mat)
        # tiled platform face + danger stencil
        shell.quad((e, -PL, FZ), (e, PL, FZ), (e, PL, PH - 0.02), (e, -PL, PH - 0.02), 'tile_white')
        f = quad_wall(trim, e + d * 0.003, -PL, PL, 0.12, 0.34, 'stencil_danger', -d, (0, 0, PL * 2 / 7.0, 1))
    # ------------------------------------------------ tracks
    for tx_ in tracks:
        add_track(shell, tx_, -(HL + 6.2), HL + 6.2, pads=tuple(-(HL + 6.0) + 1.2 + 2.4 * i for i in range(int(2 * (HL + 6.0) / 2.4))))
    # ------------------------------------------------ wall name bands (white text on orange = outer side (+x), charcoal = inner side (-x))
    band_z0, band_z1 = ((1.45, 1.95) if coved else (1.9, 2.4))
    BL = 18.0     # band spans 3 whole 12 m repeats (+-18 m) so no name is ever cut off at the ends
    quad_wall(trim, -HWL + 0.004, -BL, BL, band_z0, band_z1, f'bandmat_inner_{sid_}', 1, (0, 0, 3.0, 1))
    quad_wall(trim, HWR - 0.004, -BL, BL, band_z0, band_z1, f'bandmat_outer_{sid_}', -1, (0, 0, 3.0, 1))
    # tile band highlights (accent line)
    # ------------------------------------------------ columns
    col_ys = [-18, -12, -6, 0, 6, 12, 18]
    if cfg['pillars'] and t != 'island':
        for y in col_ys:
            if sid == 'partick':
                furn.cyl((0, y, (soffit_z + FZ) / 2), 0.32, soffit_z - FZ, mv('col_partick', 'tile_black', '#4a4d52', rough=0.15, tex='tile'), seg=8)
                furn.cyl((0, y, 1.5), 0.325, 0.25, mv('col_partick_band', 'sign_orange', '#f0601a'), seg=8)
                furn.cyl((0, y, 0.12), 0.34, 0.24, mv('col_partick_base', 'plastic_grey', '#6c8a96'), seg=8)
            else:
                furn.cyl((0, y, (soffit_z + FZ) / 2), 0.30, soffit_z - FZ, mv('col_black', 'tile_black', cfg['vault2_hex'], rough=0.12, tex='tile'), seg=16)
                furn.cyl((0, y, 0.1), 0.34, 0.2, 'steel_dark', seg=16)
    elif t == 'side' or t == 'split':
        for y in col_ys:
            if t == 'side': furn.box((0, y, (soffit_z + FZ) / 2), (0.5, 0.5, soffit_z - FZ), wall_tile)
    # fence between the tracks at side stations
    if t == 'side':
        for sgn in (-1, 1):
            q = furn.quad_uv((sgn * 1.0, -PL, FZ), (sgn * 1.0, PL, FZ), (sgn * 1.0, PL, 2.2), (sgn * 1.0, -PL, 2.2), 'fence_mesh', (0, 0, PL * 2 / 1.0, 2.4 / 1.0))
            q[furn.fx] = 1
    if t == 'split':   # glass screen on the island edge facing the side-platform track
        ex = ph if 'ph' in dir() else 1.6
        furn.box((ex + 0.0, 0, PH + 0.8), (0.02, 2 * PL, 1.6), 'glass_clear')
        for y in range(-22, 23, 2): furn.box((ex, y, PH + 0.85), (0.06, 0.06, 1.7), 'steel_bright')
    # ------------------------------------------------ benches, bins, clocks, cctv, adverts, signs, lights
    def bench(x, y, face):   # bench with wood slats, long axis along Y
        for yy in (-0.85, 0.85):
            furn.box((x, y + yy, PH + 0.22), (0.45, 0.05, 0.44), 'sign_orange')
        for i in range(5): furn.box((x + face * (-0.17 + i * 0.085), y, PH + 0.45), (0.07, 2.0, 0.03), 'wood_bench')
        furn.box((x - face * 0.2, y, PH + 0.72), (0.03, 2.0, 0.3), 'wood_bench')
    for (xa, xb) in plats:
        if t == 'island':
            for y in (-15, 0, 15): bench((xa + xb) / 2, y, 1); furn.cyl(((xa + xb) / 2 + 0.6, y + 4.5, PH + 0.45), 0.24, 0.9, 'steel_dark', seg=10)
        else:
            wallx = xa if abs(xa) > abs(xb) else xb
            fc = 1 if wallx < 0 else -1
            for y in (-16, -4, 8, 18): bench(wallx + fc * 0.45, y, fc)
            furn.cyl((wallx + fc * 0.5, 13, PH + 0.45), 0.24, 0.9, 'steel_dark', seg=10)
    # adverts on the walls (atlas cells) and info boards
    cells = [(0, 0), (1, 1), (2, 2), (3, 3), (0, 2), (2, 0), (1, 3), (3, 1)]
    wz0 = PH + 0.35
    for i, y in enumerate((-17.5, -9.5, -1.5, 6.5, 14.5, 21.0)):
        c, r = cells[i % len(cells)]
        rect = (c / 4, 1 - (r + 1) / 4, (c + 1) / 4, 1 - r / 4)
        quad_wall(signs, -HWL + 0.01, y - 0.45, y + 0.45, wz0 if not coved else wz0 - 0.1, wz0 + 1.3 if not coved else wz0 + 1.2, 'advert_atlas', 1, rect)
        c, r = cells[(i + 3) % len(cells)]
        rect = (c / 4, 1 - (r + 1) / 4, (c + 1) / 4, 1 - r / 4)
        quad_wall(signs, HWR - 0.01, y - 0.45, y + 0.45, wz0 if not coved else wz0 - 0.1, wz0 + 1.3 if not coved else wz0 + 1.2, 'advert_atlas', -1, rect)
    # line diagram panels (route map strip + roundel header)
    for sgx, hw_ in ((1, -HWL), (-1, HWR)):
        for y in (-12.0, 12.0):
            quad_wall(signs, hw_ + sgx * 0.012, y - 0.8, y + 0.8, wz0 + 0.5 if not coved else wz0 + 0.3, wz0 + 0.72 if not coved else wz0 + 0.52, 'route_map_panel', sgx, (0, 0, 1, 1))
    # hanging name boards (3.0 x 0.55) along the platform centre line(s)
    for (xa, xb) in plats:
        xc = (xa + xb) / 2
        sof_here = ceil_z(xc); hang_z = sof_here - 0.55 - 0.15
        for y in (-12, 12):
            signs.box((xc, y, hang_z + 0.4), (0.02, 0.02, 0.7), 'steel_dark') if False else None
            signs.cyl((xc, y, (hang_z + sof_here) / 2 + 0.3), 0.012, sof_here - hang_z - 0.5, 'steel_dark', seg=6)
            for sy, sf in ((0.03, -1), (-0.03, 1)):
                pass
            # board is long axis along X? boards face along the platform (readable from the platform): normal along Y
            yb = y
            p0 = (xc - 1.5, yb + 0.03, hang_z); p1 = (xc + 1.5, yb + 0.03, hang_z); p2 = (xc + 1.5, yb + 0.03, hang_z + 0.55); p3 = (xc - 1.5, yb + 0.03, hang_z + 0.55)
            signs.box((xc, yb, hang_z + 0.275), (3.0, 0.04, 0.55), 'sign_orange')
            q = signs.quad_uv(p0, p1, p2, p3, f'board_{sid_}'); q[signs.fx] = 1
            if q.normal.y < 0: q.normal_flip()
            p0 = (xc + 1.5, yb - 0.03, hang_z); p1 = (xc - 1.5, yb - 0.03, hang_z); p2 = (xc - 1.5, yb - 0.03, hang_z + 0.55); p3 = (xc + 1.5, yb - 0.03, hang_z + 0.55)
            q = signs.quad_uv(p0, p1, p2, p3, f'board_{sid_}'); q[signs.fx] = 1
            if q.normal.y > 0: q.normal_flip()
    # direction signs 'Inner | Outer' hanging near the platform ends
    for (xa, xb) in plats:
        xc = (xa + xb) / 2
        sof_here = ceil_z(xc); hang_z = sof_here - 0.55 - 0.15
